#include "tessiq/codegen/pack.h"

#include <cstddef>
#include <string>
#include <string_view>

#include "tessiq/support/result.h"

namespace tessiq::codegen {

namespace {

/// An unsigned integer of exactly this many bytes, which is how a copy sees an element.
///
/// Empty for a size with no such type. Only the width matters, so a dtype the emitter cannot
/// spell still packs.
std::string_view word_type(std::size_t element_bytes) {
  switch (element_bytes) {
  case 1:
    return "unsigned char";
  case 2:
    return "unsigned short";
  case 4:
    return "unsigned int";
  case 8:
    return "unsigned long long";
  default:
    return {};
  }
}

} // namespace

std::string pack_name(std::size_t element_bytes, std::size_t rank) {
  return "tessiq_pack_b" + std::to_string(element_bytes) + "_r" + std::to_string(rank);
}

Result<std::string> pack_source(std::size_t element_bytes, std::size_t rank) {
  const std::string_view word = word_type(element_bytes);
  if (word.empty()) {
    return unsupported("no integer type is " + std::to_string(element_bytes) +
                       " bytes wide, so a pack kernel cannot move one element at a time");
  }
  if (rank > kMaxPackRank) {
    return unsupported("pack kernels are written for up to " + std::to_string(kMaxPackRank) +
                       " axes, got " + std::to_string(rank));
  }

  const std::string name = pack_name(element_bytes, rank);

  std::string source = "// Generated by tessiq. Do not edit.\n";
  source += "typedef " + std::string(word) + " word_t;\n\n";
  source += "extern \"C\" __global__ void " + name + "(\n";
  source += "    const word_t* __restrict__ p_in,\n";
  source += "    word_t* __restrict__ p_out,\n";
  source += "    long long n";
  for (std::size_t axis = 0; axis < rank; ++axis) {
    source += ",\n    long long e" + std::to_string(axis);
  }
  for (std::size_t axis = 0; axis < rank; ++axis) {
    source += ",\n    long long s" + std::to_string(axis);
  }
  source += ") {\n";
  source += "  long long i = blockIdx.x * (long long)blockDim.x + threadIdx.x;\n";
  source += "  if (i >= n) return;\n\n";

  if (rank == 0) {
    // A scalar. There is one element, at the start of both buffers.
    source += "  p_out[0] = p_in[0];\n}\n";
    return source;
  }

  // The destination is packed, so the thread's index taken apart from the last axis forwards is
  // the coordinate in both tensors. Multiplying each coordinate by the source's own step is what
  // turns it back into a position in a buffer laid out some other way.
  source += "  long long rest = i;\n";
  source += "  long long offset = 0;\n";
  source += "  long long c;\n";
  for (std::size_t j = rank; j > 0; --j) {
    const std::string axis = std::to_string(j - 1);
    source += "  c = rest % e";
    source += axis;
    source += "; rest /= e";
    source += axis;
    source += "; offset += c * s";
    source += axis;
    source += ";\n";
  }
  source += "\n  p_out[i] = p_in[offset];\n}\n";
  return source;
}

} // namespace tessiq::codegen
