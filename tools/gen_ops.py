"""Turns ops.toml into the C++ operation table and the coverage document.

Both outputs are checked in, so a build needs no generator and a reviewer sees what changed.
`--check` verifies they match the source, which is what stops an edit to a generated file from
surviving.

Run with: python tools/gen_ops.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

# tomllib is standard from 3.11. The project supports 3.10, where tomli is the same parser under
# its original name.
if sys.version_info >= (3, 11):
    import tomllib
else:
    import tomli as tomllib

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "ops.toml"
TABLE = ROOT / "csrc" / "tessiq" / "passes" / "op_table.inc"
COVERAGE = ROOT / "docs" / "op_coverage.md"

BANNER = "Generated by tools/gen_ops.py from ops.toml. Do not edit."

CATEGORIES = {
    "elementwise": "kElementwise",
    "reduction": "kReduction",
    "matmul": "kMatmul",
}


def load() -> list[dict[str, Any]]:
    """The operations, checked."""
    with SOURCE.open("rb") as handle:
        ops: list[dict[str, Any]] = tomllib.load(handle)["op"]

    for op in ops:
        if op["category"] not in CATEGORIES:
            raise SystemExit(f"{op['name']}: unknown category {op['category']!r}")
        if op["category"] == "elementwise" and not op.get("expression"):
            raise SystemExit(f"{op['name']}: elementwise operations need an expression")
        if op["category"] != "elementwise" and op.get("expression"):
            raise SystemExit(f"{op['name']}: only elementwise operations have an expression")

    spelled = [name for op in ops for name in (op["name"], *op["aten"])]
    if len(set(spelled)) != len(spelled):
        raise SystemExit("the same spelling appears twice")

    return ops


def spellings(ops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """One row per spelling, sorted, since the C++ table is looked up by name."""
    rows = [{**op, "spelling": name} for op in ops for name in (op["name"], *op["aten"])]
    return sorted(rows, key=lambda row: row["spelling"])


def escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def table(ops: list[dict[str, Any]]) -> str:
    rows = spellings(ops)
    lines = [
        f"// {BANNER}",
        "//",
        "// Included at namespace scope in op_table.cpp. The declaration is here rather than there",
        "// because the element count is one per aten spelling and not one per operation, so the",
        "// generator is the only thing that can keep it right.",
        "// clang-format off",
        f"constexpr std::array<OpInfo, {len(rows)}> kOps{{{{",
    ]
    for row in rows:
        expression = escape(row.get("expression", ""))
        lines.append(
            f'    {{"{row["spelling"]}", '
            f'"{row["name"]}", '
            f"OpCategory::{CATEGORIES[row['category']]}, "
            f"{row['arity']}, "
            f'"{expression}", '
            f"{'true' if row['kernel'] else 'false'}}},"
        )
    lines.append("}};")
    lines.append("// clang-format on")
    return "\n".join(lines) + "\n"


def coverage(ops: list[dict[str, Any]]) -> str:
    """One row per operation rather than per spelling, which is what a reader wants."""
    with_kernel = sum(1 for op in ops if op["kernel"])
    lines = [
        "# Operation coverage",
        "",
        f"<!-- {BANNER} -->",
        "",
        f"{with_kernel} of {len(ops)} operations have a kernel. Everything else reaches PyTorch's",
        "CPU implementation through the fallback, which is correct and costs two transfers.",
        "",
        "Elementwise operations can share a kernel with their neighbours. Anything else reads",
        "positions it is not writing, so it runs on its own however many kernels it has.",
        "",
        "| Operation | ATen | Category | Kernel |",
        "|---|---|---|---|",
    ]
    for op in sorted(ops, key=lambda op: (op["category"], op["name"])):
        aten = "<br>".join(f"`{name}`" for name in op["aten"])
        mark = "yes" if op["kernel"] else "no"
        lines.append(f"| `{op['name']}` | {aten} | {op['category']} | {mark} |")

    lines += [
        "",
        "Regenerate with `python tools/gen_ops.py` after editing",
        "[`ops.toml`](../ops.toml).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the generated files are out of date"
    )
    arguments = parser.parse_args()

    ops = load()
    wanted = {TABLE: table(ops), COVERAGE: coverage(ops)}

    if arguments.check:
        stale = [
            path for path, text in wanted.items() if not path.exists() or path.read_text() != text
        ]
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: python tools/gen_ops.py", file=sys.stderr)
            return 1
        return 0

    for path, text in wanted.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
