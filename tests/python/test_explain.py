"""One model's whole compilation, reported in one place.

What these check is that the report says what happened rather than what the reporting code
believes happened. The two come apart the moment a report holds its own copy of something the
compiler decides, which is why the pipeline and the kernels are read back from the compiler here
rather than written down.
"""

from __future__ import annotations

import pytest
import torch
from torch import nn

import tessiq
from tessiq.explain import SECTIONS, explain, explain_graph, pass_by_pass
from test_models import EncoderBlock


def model() -> nn.Module:
    torch.manual_seed(0)
    return nn.Sequential(nn.Linear(32, 32), nn.Tanh()).eval()


@pytest.fixture(autouse=True)
def _fresh_dynamo() -> None:
    torch._dynamo.reset()


def test_every_section_appears() -> None:
    report = explain(model(), torch.randn(4, 32))
    for section in SECTIONS:
        assert f"== {section} ==" in report


def test_only_the_sections_asked_for() -> None:
    report = explain(model(), torch.randn(4, 32), sections=("summary", "schedule"))
    assert "== summary ==" in report
    assert "== schedule ==" in report
    assert "== graph ==" not in report


def test_an_unknown_section_is_refused() -> None:
    # Named rather than ignored, because a typo that silently drops a section is a report that
    # quietly answers a different question.
    with pytest.raises(ValueError, match="unknown section"):
        explain(model(), torch.randn(4, 32), sections=("summary", "kernles"))


def test_the_pipeline_is_the_one_the_backend_runs() -> None:
    changes = pass_by_pass(tessiq.import_graph(tessiq.capture(model(), torch.randn(4, 32))))
    assert [change.name for change in changes] == tessiq.default_pipeline()


def test_a_pass_that_changes_nothing_says_so() -> None:
    # layout-assign only acts when an operand's layout has to be materialised, which this graph
    # does not need. A report that showed a diff for it would be describing a pass that did not
    # run.
    report = explain(model(), torch.randn(4, 32), sections=("passes",))
    assert "layout-assign: nothing changed" in report


def test_the_diff_shows_what_an_annotation_added() -> None:
    changes = pass_by_pass(tessiq.import_graph(tessiq.capture(model(), torch.randn(4, 32))))
    marked = next(change for change in changes if change.name == "mark-supported")
    assert marked.changed
    # Paired, old line then new, so the attribute that appeared is visible between them.
    lines = marked.diff.splitlines()
    assert lines[0].startswith("-")
    assert lines[1].startswith("+")
    assert "tessiq.supported" not in lines[0]
    assert "tessiq.supported" in lines[1]


def test_the_schedule_covers_every_operation() -> None:
    graph = tessiq.capture(model(), torch.randn(4, 32))
    report = explain_graph(graph, sections=("schedule",))
    for node in graph.graph.nodes:
        if node.op == "call_function":
            assert node.name in report


def test_the_host_target_says_why_it_has_no_kernels() -> None:
    # The easiest way to be confused by this tool is to run it without a device and conclude the
    # compiler cannot do anything.
    report = explain(model(), torch.randn(4, 32), sections=("summary",))
    assert "kernels" in report
    assert "host reference" in report


@pytest.mark.cuda
def test_the_kernels_are_the_recipe_s_own() -> None:
    if tessiq.gpu_count() == 0:
        pytest.skip("needs a gpu")

    example = torch.randn(4, 9, 32)
    net = EncoderBlock().eval()
    recipe = tessiq.build_recipe(tessiq.capture(net, example), tessiq.gpu, use_cache=False)
    report = explain(net, example, device=tessiq.gpu, sections=("kernels",))
    for name in recipe.kernels:
        assert f"%{name}" in report


@pytest.mark.cuda
def test_a_symbolic_graph_reports_that_its_extents_arrive_later() -> None:
    if tessiq.gpu_count() == 0:
        pytest.skip("needs a gpu")

    report = explain(
        EncoderBlock().eval(),
        torch.randn(4, 9, 32),
        device=tessiq.gpu,
        dynamic=True,
        sections=("summary", "kernels"),
    )
    assert "shapes" in report
    assert "known at the call" in report
    assert "extents at the launch" in report


@pytest.mark.cuda
def test_the_source_is_the_generated_kernel() -> None:
    if tessiq.gpu_count() == 0:
        pytest.skip("needs a gpu")

    report = explain(
        EncoderBlock().eval(),
        torch.randn(4, 9, 32),
        device=tessiq.gpu,
        sections=("kernels",),
        source=True,
    )
    assert "__global__" in report
    assert "Generated by tessiq" in report


def test_an_operation_on_the_host_is_not_reported_as_on_the_device() -> None:
    # A node returning more than one tensor has its first result renamed after the getitem that
    # reads it, so it is missing from the recipe's device map. The default for a missing entry has
    # to be the host. `tessiq.cpu` looks like the right default and is not: it is the reference
    # device and its type is `tessiq`, so using it reported every such node as on the device.
    #
    # topk is the case because it returns values and indices and nothing runs it. This test used a
    # residual block until phase 11 moved convolution to the device and decomposed batch norm, at
    # which point it had no multi-result node left on the host and failed for the wrong reason.
    class TopK(nn.Module):
        def forward(self, x: torch.Tensor) -> torch.Tensor:
            values, _ = torch.topk(torch.relu(x), 3, dim=-1)
            return values * 2.0

    graph = tessiq.capture(TopK(), torch.randn(4, 8))
    recipe = tessiq.build_recipe(graph, tessiq.cpu, use_cache=False)
    assert "topk" not in recipe.devices, "the case this guards needs a node missing from the map"

    report = explain_graph(graph, sections=("schedule",))
    line = next(line for line in report.splitlines() if "aten.topk" in line)
    assert "host" in line.split("aten.topk.default")[-1], line
